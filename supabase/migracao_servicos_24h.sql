-- Migração: serviço de 24h (07:00 -> 07:00), saída automática e estacionamento permanente.
-- Apenas ACRESCENTA colunas/tabela/função; nenhum dado existente é apagado.

alter table public.movimentacoes
  add column if not exists permanente boolean not null default false,
  add column if not exists saida_automatica boolean not null default false,
  add column if not exists base_turno timestamptz,
  add column if not exists servico_id bigint,
  add column if not exists usuario_entrada text,
  add column if not exists usuario_saida text,
  add column if not exists obs_permanencia text;

create table if not exists public.servicos (
  id bigint generated by default as identity primary key,
  inicio timestamptz not null unique,
  fim timestamptz not null,
  iniciado_em timestamptz not null default now(),
  usuario text,
  sentinela text,
  observacao text
);
alter table public.servicos enable row level security;
drop policy if exists "Permitir tudo em servicos" on public.servicos;
create policy "Permitir tudo em servicos" on public.servicos for all using (true) with check (true);

create index if not exists idx_mov_status on public.movimentacoes(status);
create index if not exists idx_mov_created on public.movimentacoes(created_at);

-- Dá saída automática aos veículos NÃO permanentes cujo serviço (07:00 -> 07:00) já terminou.
-- A hora de saída gravada é o fim do serviço em que o veículo entrou.
create or replace function public.fechar_servicos_vencidos()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare n integer;
begin
  with alvo as (
    select id,
      date_trunc('day', (coalesce(base_turno, created_at) at time zone 'America/Recife') - interval '7 hours')
        + interval '1 day 7 hours' as fim_local
    from movimentacoes
    where status = 'Em Trânsito' and permanente = false
  )
  update movimentacoes m
     set status = 'Concluído',
         saida_automatica = true,
         hora_saida = to_char(a.fim_local, 'DD/MM/YYYY HH24:MI:SS'),
         usuario_saida = 'automático (fim do serviço)'
    from alvo a
   where m.id = a.id
     and (a.fim_local at time zone 'America/Recife') <= now();
  get diagnostics n = row_count;
  return n;
end;
$$;
